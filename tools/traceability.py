"""Build a requirement -> tests traceability table from '# Verifies:' comments.

Usage:  python tools/traceability.py
Writes: docs/traceability.md
Exit code 1 if some requirement has no test.
"""

import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

REQUIREMENTS = {
    "R1": "Empty, whitespace-only, missing or non-string question rejected (422)",
    "R2": "Question longer than 500 characters rejected (422)",
    "R3": "Surrounding whitespace removed",
    "R4": "FAQ question gets the LLM answer (answered)",
    "R5": "Out-of-scope question gets fixed message (out_of_scope)",
    "R6": "Unclear message gets rephrase request (unclear)",
    "R7": "Turkish characters and emoji handled",
    "R8": "LLM failure gives generic 503",
    "R9": "Response format is always {answer, status}; /health works",
    "R10": "Prompt contains all FAQ entries and the only-from-FAQ rule",
}

VERIFIES = re.compile(r"#\s*Verifies:\s*(.+)")
TEST_DEF = re.compile(r"def (test_\w+)")


def collect():
    """Return {requirement_id: [test names]} found in the tests folder."""
    trace = defaultdict(list)
    tests_dir = ROOT / "tests"
    for path in sorted(tests_dir.rglob("test_*.py")):
        pending = []
        for line in path.read_text(encoding="utf-8").splitlines():
            match = VERIFIES.search(line)
            if match:
                pending = [r.strip() for r in match.group(1).split(",")]
                continue
            definition = TEST_DEF.search(line)
            if definition:
                for req in pending:
                    trace[req].append(f"{path.relative_to(tests_dir)}::{definition.group(1)}")
                pending = []
    return trace


def main():
    trace = collect()
    lines = [
        "# Traceability matrix",
        "",
        "Generated by `python tools/traceability.py`. Do not edit by hand.",
        "",
        "| Requirement | Description | Test functions | Count |",
        "|---|---|---|---|",
    ]
    for req, description in REQUIREMENTS.items():
        tests = trace.get(req, [])
        names = "<br>".join(tests) if tests else "**NO TEST**"
        lines.append(f"| {req} | {description} | {names} | {len(tests)} |")

    output = "\n".join(lines) + "\n"
    (ROOT / "docs" / "traceability.md").write_text(output, encoding="utf-8")
    print(output)

    missing = [req for req in REQUIREMENTS if not trace.get(req)]
    if missing:
        print("Requirements without tests:", ", ".join(missing))
        raise SystemExit(1)


if __name__ == "__main__":
    main()